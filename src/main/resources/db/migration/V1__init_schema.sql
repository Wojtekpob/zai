CREATE TABLE app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE series (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    min_value DOUBLE PRECISION NOT NULL,
    max_value DOUBLE PRECISION NOT NULL,
    color VARCHAR(7) NOT NULL,
    icon VARCHAR(50),
    unit VARCHAR(20),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT chk_series_min_max CHECK (min_value < max_value)
);

CREATE TABLE sensors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    series_id BIGINT NOT NULL,
    api_key_hash VARCHAR(64) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_measurement_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_sensors_series FOREIGN KEY (series_id) REFERENCES series(id) ON DELETE CASCADE
);

CREATE INDEX idx_sensors_api_key_hash ON sensors(api_key_hash);
CREATE INDEX idx_sensors_series_id ON sensors(series_id);

CREATE TABLE measurements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    series_id BIGINT NOT NULL,
    sensor_id BIGINT,
    val DOUBLE PRECISION NOT NULL,
    timestamp TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_measurements_series FOREIGN KEY (series_id) REFERENCES series(id) ON DELETE CASCADE,
    CONSTRAINT fk_measurements_sensor FOREIGN KEY (sensor_id) REFERENCES sensors(id) ON DELETE SET NULL
);

CREATE INDEX idx_measurements_series_time ON measurements(series_id, timestamp);
CREATE INDEX idx_measurements_timestamp ON measurements(timestamp);

CREATE TABLE revoked_tokens (
    token_id VARCHAR(255) PRIMARY KEY,
    expiry_date TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_revoked_tokens_expiry ON revoked_tokens(expiry_date);
